"""Writes the graph of the process documents as JSON-LD, derived from the
same headers doclint.py reads for its indexes. The documents are the source
of truth: the graph file is generated, never edited by hand.

    docgraph.py --repo DIR --templates REF [--source SRC]          check
    docgraph.py --repo DIR --templates REF --write                 write

SRC is where the documents are read, "index" (the default), "worktree" or
a commit. REF is the line, origin/<line>, where the areas page is read.
The check exits 1 when docs/index/graph.json at SRC is not what the
documents give, or docs/index/context.json is not there. --write puts the
graph in the working tree.

A node is each document doclint.py indexes lists, each feature directory,
each area a document names, and each Apache JIRA ticket, release or commit
an import record names. A link is written only where a header or a table
states it:

  dcterms:subject      a document names an area in its Areas row
  dcterms:isPartOf     a document lives in a feature directory, or is a
                       design record that defines the feature's REQ ids
  dcterms:replaces     a decision record's Supersedes row names a record
  dcterms:references   a row of a document's revision history names a
                       decision record
  oslc_rm:elaborates   a design or fix record's References row links a
                       feature spec
  prov:wasDerivedFrom  an import record's header names an Apache JIRA
                       ticket, release or commit

The output is the same bytes for the same tree: nodes sorted by id, keys
sorted, no date of writing and no absolute path. Every address in it is
relative to the graph file, or Apache's own, so it holds after the
repository moves or is renamed. Python 3, standard library only.
"""

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import doclint  # noqa: E402
from markdown import Markdown  # noqa: E402

GRAPH = doclint.INDEX_DIR + "/graph.json"
CONTEXT = doclint.INDEX_DIR + "/context.json"
NOTE = "Generated by tools/chronitondb/docgraph.py --write from the document control table of each document. Never edited by hand."
# The types of a node by the kind of its document: an established class
# where one fits, the document kind itself under dcterms:type always.
TYPES = {"Feature spec": ["oslc_rm:RequirementCollection", "schema:DigitalDocument"]}
APACHE_SOURCES = ("apache-cherry-pick", "apache-merge")
LINE = re.compile(r"\bLine `(chronitondb-[a-z0-9.]+)`")


def here(path):
    """The address of a repository path, relative to the graph file."""
    return os.path.relpath(path, doclint.INDEX_DIR).replace(os.sep, "/")


def graph(repo, where, rules_ref):
    source = doclint.Source(repo, where)
    entries = doclint.indexed_documents(repo, where)
    by_record = {entry["id"]: entry["path"] for entry in entries if entry["kind"] == "Decision record" and entry["id"]}
    nodes = {}

    def node(name, **values):
        found = nodes.setdefault(name, {"@id": name})
        for key, value in values.items():
            if value in ("", None, []):
                continue
            if isinstance(value, list):
                found[key] = sorted(set(found.get(key, [])) | set(value))
            else:
                found[key] = value
        return found

    features = {}
    for path in doclint.docs_at(repo, where):
        parts = path.split("/")
        match = doclint.DIR_FORM.match(parts[2]) if path.startswith("docs/design/") and len(parts) >= 4 else None
        if match and match.group(1):
            features[match.group(1)] = "docs/design/%s/" % parts[2]
    for key, folder in features.items():
        node(here(folder) + "/", **{"@type": ["Feature"], "identifier": key})
    known = doclint.areas_at(repo, rules_ref) or []
    for entry in entries:
        path = entry["path"]
        text = source.read(path) or ""
        doc = Markdown(path, text)
        values = {"@type": TYPES.get(entry["kind"], ["schema:DigitalDocument"]), "type": entry["kind"], "title": entry["title"],
                  "status": entry["status"], "version": entry.get("version", ""), "identifier": entry.get("id") or path}
        line = LINE.search(entry["references"])
        values["line"] = entry.get("line") or (line.group(1) if line else "")
        values["source"] = entry.get("source", "")
        values["date"] = entry.get("date", "")
        own = node(here(path), **values)
        for name in entry["areas"] or []:
            area = here(doclint.AREAS_PAGE) + "#" + name
            node(area, **{"@type": ["skos:Concept"], "prefLabel": name, "inScheme": here(doclint.AREAS_PAGE)} if name in known else {"@type": ["skos:Concept"], "prefLabel": name})
            node(here(path), areas=[area])
        # The feature a document belongs to: its directory, or the key of
        # the REQ ids a design record defines.
        parts = path.split("/")
        keys = set()
        if path.startswith("docs/design/") and len(parts) >= 4:
            match = doclint.DIR_FORM.match(parts[2])
            if match and match.group(1):
                keys.add(match.group(1))
        if entry["kind"] in ("Design record", "Fix record"):
            keys.update(rid.split("-")[1] for rid, _ in doclint.requirement_definitions(doc, r"REQ-[A-Z]{3,5}-[0-9]{3}"))
            spec = doclint.spec_link_of(entry["references"], path, source)
            if spec and any(other["path"] == spec for other in entries):
                node(here(path), elaborates=[here(spec)])
        node(here(path), isPartOf=[here(features[key]) + "/" for key in keys if key in features])
        if entry["kind"] == "Decision record":
            names = doclint.RECORD_REF.findall(re.sub(r"\([^)]*\)", "", entry["supersedes"]))
            node(here(path), replaces=[here(by_record[name]) for name in names if name in by_record])
        cited = []
        for _, cells in doclint.revision_rows(doc)[1]:
            if len(cells) >= 4:
                cited += [name for name in doclint.RECORD_REF.findall(re.sub(r"\([^)]*\)", "", cells[3])) if name in by_record]
        node(here(path), references=[here(by_record[name]) for name in cited])
        if entry["kind"] == "Import record":
            derived = []
            for name in entry["jira"]:
                ticket = "https://issues.apache.org/jira/browse/" + name
                node(ticket, **{"@type": ["prov:Entity"], "identifier": name})
                derived.append(ticket)
            for name in entry["upstream"]:
                if entry.get("source") in APACHE_SOURCES:
                    address = "https://github.com/apache/cassandra/" + ("releases/tag/" if name.startswith("cassandra-") else "commit/") + name
                    node(address, **{"@type": ["prov:Entity"], "identifier": name})
                    derived.append(address)
                else:
                    node(here(path), upstreamRevision=[name])
            node(here(path), wasDerivedFrom=derived)
    return {"@context": os.path.basename(CONTEXT), "@id": os.path.basename(GRAPH), "description": NOTE,
            "@graph": [nodes[name] for name in sorted(nodes)]}


def render(data):
    return json.dumps(data, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv):
    repo, rules_ref, where, write = None, None, "index", False
    index = 0
    while index < len(argv):
        word = argv[index]
        if word in ("--repo", "--templates", "--source") and index + 1 < len(argv):
            if word == "--repo":
                repo = argv[index + 1]
            elif word == "--templates":
                rules_ref = argv[index + 1]
            else:
                where = argv[index + 1]
            index += 2
            continue
        if word == "--write":
            write = True
            index += 1
            continue
        sys.stderr.write(__doc__)
        return 2
    if not repo or not rules_ref:
        sys.stderr.write(__doc__)
        return 2
    if write:
        where = "worktree"
    source = doclint.Source(repo, where)
    text = render(graph(repo, where, rules_ref))
    failed = 0
    if source.read(CONTEXT) is None:
        sys.stderr.write("%s:0: the context of the graph is not there. It is a file of the repository, kept by hand\n" % CONTEXT)
        failed = 1
    if write:
        if source.read(GRAPH) != text:
            full = os.path.join(repo, GRAPH)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w", encoding="utf-8") as handle:
                handle.write(text)
            print("graph %s written" % GRAPH)
        else:
            print("graph %s current" % GRAPH)
        return failed
    if source.read(GRAPH) != text:
        sys.stderr.write("%s:0: is not the graph the documents give now. docgraph.py --write regenerates it, then commit it with the change\n" % GRAPH)
        failed = 1
    print("graph %s" % ("stale" if failed else "current"))
    return failed


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
